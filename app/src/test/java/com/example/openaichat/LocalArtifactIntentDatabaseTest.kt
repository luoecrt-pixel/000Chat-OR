package com.example.openaichat

import android.content.Context
import android.database.sqlite.SQLiteDatabase
import android.database.sqlite.SQLiteException
import org.json.JSONArray
import org.json.JSONObject
import org.junit.After
import org.junit.Assert.*
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment
import org.robolectric.annotation.Config
import org.robolectric.annotation.SQLiteMode
import java.io.File
import java.security.MessageDigest

/** Uses production transactions, including a real SQLite abort after physical publication. */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [35])
@SQLiteMode(SQLiteMode.Mode.NATIVE)
class LocalArtifactIntentDatabaseTest {
    private lateinit var context: Context
    private val files = mutableListOf<File>()
    private val chat = "artifact-intent"
    private val request = "request-artifact"
    private val call = "provider-call-original"
    private val tool = "create_local_text_file"
    private val argsHash = StreamingJsonRequestBody.sha256("original arguments")
    private val content = "original generated bytes\n"

    @Before fun setup() {
        context = RuntimeEnvironment.getApplication()
        SQLiteDatabase.deleteDatabase(context.getDatabasePath("astra_chats.db"))
    }

    @After fun cleanup() {
        files.forEach(File::delete)
        SQLiteDatabase.deleteDatabase(context.getDatabasePath("astra_chats.db"))
    }

    private fun prepare(db: ChatDatabase, provider: String = "openrouter") {
        db.ensureChat(chat, "Artifact journal")
        db.upsertCurrentChat(chat, "Artifact journal", null, "high", listOf(JSONObject()
            .put("role", "user").put("text", "Create file").put("request_id", request).put("provider", provider)))
        db.startRequestAccounting(chat, request, provider, "test-model", "inert-key")
        db.setActiveResponse(chat, null, request, "", "in_progress", 1L,
            "high", "high", false, 0, 0, false)
    }

    private fun plan(): JSONObject {
        val directory = File(context.filesDir, "generated").apply { mkdirs() }
        val target = File.createTempFile("intent-", ".txt", directory).apply { delete(); files += this }
        val hash = LocalUtf8FilePatch.hex(MessageDigest.getInstance("SHA-256")
            .digest(content.toByteArray(Charsets.UTF_8)))
        val attachment = JSONObject().put("id", "local-test").put("path", target.path)
            .put("text_path", target.path).put("sha256", hash).put("size", content.toByteArray().size)
        return JSONObject().put("version", 1).put("artifact", JSONObject().put("ok", true)
            .put("type", "local_file").put("path", target.path).put("file_id", "local-test")
            .put("filename", target.name).put("mime_type", "text/plain").put("sha256", hash)
            .put("size_bytes", content.toByteArray().size).put("attachment", attachment))
            .put("publication", JSONObject().put("target_path", target.path)
                .put("expected_sha256", hash).put("expected_bytes", content.toByteArray().size))
    }

    private fun begin(db: ChatDatabase, plan: JSONObject): JSONObject =
        db.beginLocalArtifactIntentIfActive(chat, request, call, tool, argsHash, plan)!!

    private fun publish(plan: JSONObject): File = File(plan.getJSONObject("artifact").getString("path"))
        .apply { writeText(content) }

    private fun complete(db: ChatDatabase, intent: JSONObject): JSONObject? =
        db.completeLocalArtifactIntent(chat, request, call, tool, argsHash,
            intent.getString("plan_sha256"), intent.getJSONObject("plan").getJSONObject("artifact"))

    private fun indexedCount(db: ChatDatabase): Int = db.readableDatabase
        .rawQuery("SELECT COUNT(*) FROM local_artifacts", null).use { it.moveToFirst(); it.getInt(0) }

    @Test fun onlyCapturedActiveOpenRouterOwnerCanAuthorizePublication() {
        ChatDatabase(context).use { db ->
            prepare(db, "openai")
            val plan = plan()
            assertNull(db.beginLocalArtifactIntentIfActive(chat, request, call, tool, argsHash, plan))
            assertNull(db.beginLocalArtifactIntentIfActive(chat, "replacement", call, tool, argsHash, plan))
            assertTrue(db.listLocalArtifactIntents().isEmpty())
            assertFalse(File(plan.getJSONObject("artifact").getString("path")).exists())
        }
    }

    @Test fun duplicateClaimNeverGrantsAnotherPublicationAndIdentityCannotChange() {
        ChatDatabase(context).use { db ->
            prepare(db)
            val plan = plan()
            assertTrue(begin(db, plan).getBoolean("_inserted"))
            assertFalse(begin(db, plan).getBoolean("_inserted"))
            try {
                db.beginLocalArtifactIntentIfActive(chat, request, call, tool,
                    StreamingJsonRequestBody.sha256("changed arguments"), plan)
                fail("A provider call ID cannot authorize different arguments")
            } catch (_: IllegalStateException) { }
            try {
                val changedPlan = JsonProtocol.objectCopy(plan)
                changedPlan.getJSONObject("artifact").put("filename", "changed.txt")
                begin(db, changedPlan)
                fail("A saved publication plan is immutable")
            } catch (_: IllegalStateException) { }
            assertEquals(1, db.listLocalArtifactIntents().size)
        }
    }

    @Test fun sqliteAbortKeepsPublishedBytesAndIntentAcrossReopenWithoutRewritingFile() {
        val plan = plan()
        lateinit var savedIntent: JSONObject
        lateinit var target: File
        var modified = 0L
        ChatDatabase(context).use { db ->
            prepare(db)
            savedIntent = begin(db, plan)
            target = publish(plan)
            modified = target.lastModified()
            db.writableDatabase.execSQL("CREATE TRIGGER fail_artifact_completion BEFORE UPDATE OF state ON local_artifact_intents BEGIN SELECT RAISE(ABORT, 'injected completion failure'); END")
            try { complete(db, savedIntent); fail("Expected actual SQLite transaction failure") }
            catch (_: SQLiteException) { }
            assertEquals(0, indexedCount(db))
            assertEquals("in_flight", db.getLocalArtifactIntent(chat, request, call)!!.getString("state"))
            assertTrue(db.listAllLocalFilePaths().contains(target.path))
            assertTrue(db.listLocalFiles(chat).any { it.getString("path") == target.path })
        }
        ChatDatabase(context).use { db ->
            db.writableDatabase.execSQL("DROP TRIGGER fail_artifact_completion")
            assertEquals("completed", complete(db, savedIntent)!!.getString("state"))
            assertEquals(1, indexedCount(db))
            assertEquals(content, target.readText())
            assertEquals(modified, target.lastModified())
        }
    }

    @Test fun authorizedFileCanBeAdoptedAfterStopWithoutRevivingRequestOrMessages() {
        ChatDatabase(context).use { db ->
            prepare(db)
            val plan = plan()
            val intent = begin(db, plan)
            publish(plan)
            assertTrue(db.stopActiveRequestOnce(chat, request))
            val messagesAfterStop = db.getChat(chat)!!.getJSONArray("messages").toString()
            assertEquals("completed", complete(db, intent)!!.getString("state"))
            assertNull(db.getActiveResponse(chat))
            assertEquals(messagesAfterStop, db.getChat(chat)!!.getJSONArray("messages").toString())
            assertEquals("stopped", db.listRequestAccounting(chat).single().getString("local_status"))
            assertEquals(1, indexedCount(db))
        }
    }

    @Test fun deleteTombstoneSurvivesChatIdRecreationAndCannotAdoptOrReauthorizeOldCall() {
        ChatDatabase(context).use { db ->
            prepare(db)
            val plan = plan()
            val intent = begin(db, plan)
            val target = publish(plan)
            db.deleteChat(chat)
            assertNull(db.getChat(chat))
            assertTrue(complete(db, intent)!!.getBoolean("tombstoned"))
            assertNull(db.getChat(chat))
            prepare(db)
            val duplicate = begin(db, plan)
            assertTrue(duplicate.getBoolean("tombstoned"))
            assertFalse(duplicate.getBoolean("_inserted"))
            assertTrue(complete(db, intent)!!.getBoolean("tombstoned"))
            assertEquals(0, indexedCount(db))
            assertTrue(db.listLocalFiles(chat).isEmpty())
            assertEquals(content, target.readText())
        }
    }

    @Test fun explicitFileRemovalTombstonesPendingPublicationWithoutDeletingSharedOriginal() {
        ChatDatabase(context).use { db ->
            prepare(db)
            val plan = plan()
            val intent = begin(db, plan)
            val target = publish(plan)
            db.ensureChat("shared", "Shared original")
            db.upsertCurrentChat("shared", "Shared original", null, "high", listOf(JSONObject()
                .put("role", "user").put("text", "Keep original")
                .put("file_paths", JSONArray().put(target.path))))
            assertTrue(db.removeLocalFile(target.path))
            assertTrue(complete(db, intent)!!.getBoolean("tombstoned"))
            assertEquals(0, indexedCount(db))
            assertTrue(db.listAllLocalFilePaths().contains(target.path))
            assertEquals(content, target.readText())
        }
    }

    @Test fun absentOrMismatchedPublishedBytesCannotBecomeCompleted() {
        ChatDatabase(context).use { db ->
            prepare(db)
            val plan = plan()
            val intent = begin(db, plan)
            assertEquals("in_flight", complete(db, intent)!!.getString("state"))
            val target = publish(plan)
            target.writeText("wrong bytes")
            assertEquals("in_flight", complete(db, intent)!!.getString("state"))
            assertEquals("outcome_unknown", db.markLocalArtifactIntentUnknown(chat, request, call, tool,
                argsHash, intent.getString("plan_sha256"))!!.getString("state"))
            assertEquals(0, indexedCount(db))
            assertEquals("wrong bytes", target.readText())
        }
    }

    @Test fun openingExistingSchema25AddsIntentTableWithoutChangingStoredMessages() {
        lateinit var before: String
        ChatDatabase(context).use { db ->
            prepare(db)
            before = db.getChat(chat)!!.getJSONArray("messages").toString()
            assertEquals(25, db.readableDatabase.version)
            db.writableDatabase.execSQL("DROP TABLE local_artifact_intents")
        }
        ChatDatabase(context).use { db ->
            assertTrue(db.listLocalArtifactIntents().isEmpty())
            assertEquals(25, db.readableDatabase.version)
            assertEquals(before, db.getChat(chat)!!.getJSONArray("messages").toString())
            assertTrue(begin(db, plan()).getBoolean("_inserted"))
        }
    }
}
